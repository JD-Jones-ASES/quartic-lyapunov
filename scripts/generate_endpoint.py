#!/usr/bin/env python3
"""Generate exact real-algebraic data and kernel-checkable identity proofs.

No generated theorem uses a trusted computational decision procedure.
Fraction arithmetic produces data; ring and order proofs check it in Lean.
"""
from pathlib import Path
from fractions import Fraction as Q
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'evidence'))
from independent_replay import replay, A, MODULUS, LOWER, UPPER, add, scale, multiply, divide, determinant
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'QuarticLyapunov'
data=replay(True)
vals={f'{kind}{i}':v for kind in ['v','h','p'] for i,v in enumerate(data[kind])}
vals['detM'] = determinant(data['M'][:5])
g=data['G']
d0=g[0][0]; l10=g[1][0]/d0; l20=g[2][0]/d0
d1=g[1][1]-d0*l10*l10
l21=(g[2][1]-d0*l20*l10)/d1
d2=g[2][2]-d0*l20*l20-d1*l21*l21
vals.update(dict(d0=d0,d1=d1,d2=d2,l10=l10,l20=l20,l21=l21))
g=data['H']
md0=g[0][0]; ml10=g[1][0]/md0; ml20=g[2][0]/md0
md1=g[1][1]-md0*ml10*ml10
ml21=(g[2][1]-md0*ml20*ml10)/md1
md2=g[2][2]-md0*ml20*ml20-md1*ml21*ml21
vals.update(dict(md0=md0,md1=md1,md2=md2,ml10=ml10,ml20=ml20,ml21=ml21))

def rat(v):
 v=Q(v)
 return str(v.numerator) if v.denominator==1 else f'({v.numerator} / {v.denominator} : ℝ)'

def poly(p,var='boundary'):
 p=list(p)
 if not p:return '(0 : ℝ)'
 s=rat(p[-1])
 for c in reversed(p[:-1]):s=f'({s}*{var}+{rat(c)})'
 return s

header='module\npublic import QuarticLyapunov.Interval\n\n/-! Exact algebraic endpoint data. Generated by scripts/generate_endpoint.py. -/\n@[expose] public noncomputable section\nnamespace QuarticLyapunov.Endpoint\n'
(OUT/'EndpointData.lean').write_text(header+'\n'.join(f'def {k} : ℝ := {poly(v.p)}\n' for k,v in vals.items())+'\nend QuarticLyapunov.Endpoint\n')

class E:
 def __init__(self,s,p):self.s,self.p=s,list(p)
 def __add__(self,o):
  o=e(o);return E(f'({self.s}+{o.s})',add(self.p,o.p))
 __radd__=__add__
 def __neg__(self):return E(f'(-{self.s})',scale(self.p,-1))
 def __sub__(self,o):return self+-e(o)
 def __rsub__(self,o):return e(o)+-self
 def __mul__(self,o):
  o=e(o);return E(f'({self.s}*{o.s})',multiply(self.p,o.p))
 __rmul__=__mul__
 def __truediv__(self,o):return self*e(Q(1)/Q(o))
 def __pow__(self,n):
  if n==0:return e(1)
  out=self
  for _ in range(n-1):out=out*self
  return out

def e(x):
 if isinstance(x,E):return x
 return E(rat(x),[Q(x)])
v={k:E(k,a.p) for k,a in vals.items()}
b=E('boundary',[0,1]);h=[v[f'h{i}'] for i in range(4)];p=[v[f'p{i}'] for i in range(5)];mom=[v[f'v{i}'] for i in range(7)]
M=[[4-4*b,-1,0,0,0],[4,4-4*b,-2,0,0],[4+4*b,2,4-4*b,-3,0],[4,4+4*b,0,4-4*b,-4],[0,3,4+4*b,-2,4-4*b],[0,0,2,4+4*b,-4],[0,0,0,1,4+4*b]]
identities={}
for i in range(7):
 identities[f'lie{i}']=(sum((e(M[i][j])*p[j] for j in range(5)),e(0)),sum((h[j]*h[i-j] for j in range(4) if 0<=i-j<4),e(0)))
for i in range(4):identities[f'kernel{i}']=(sum((mom[i+j]*h[j] for j in range(4)),e(0)),e(0))
for j in range(5):identities[f'dual{j}']=(sum((mom[i]*e(M[i][j]) for i in range(7)),e(0)),e(0))
identities['normalization']=(mom[0]+3*mom[2]+3*mom[4]+mom[6],e(1))
identities['sos0']=(v['d0'],p[0])
identities['sos1']=(2*v['d0']*v['l10'],p[1])
identities['sos2']=(v['d0']*(v['l10']**2+2*v['l20'])+v['d1'],p[2])
identities['sos3']=(2*v['d0']*v['l10']*v['l20']+2*v['d1']*v['l21'],p[3])
identities['sos4']=(v['d0']*v['l20']**2+v['d1']*v['l21']**2+v['d2'],p[4])
identities['msos0']=(v['md0'],mom[0])
identities['msos1']=(v['md0']*v['ml10'],mom[1])
identities['msos2']=(v['md0']*v['ml20'],mom[2])
identities['msos3']=(v['md0']*v['ml10']**2+v['md1'],mom[2])
identities['msos4']=(v['md0']*v['ml10']*v['ml20']+v['md1']*v['ml21'],mom[3])
identities['msos5']=(v['md0']*v['ml20']**2+v['md1']*v['ml21']**2+v['md2'],mom[4])
parts=['module\npublic import QuarticLyapunov.EndpointData\n\npublic section\nset_option maxRecDepth 4096\nset_option maxHeartbeats 0\nnamespace QuarticLyapunov.Endpoint\n']
for name,(lhs,rhs) in identities.items():
 q,r=divide(add(lhs.p,scale(rhs.p,-1)),MODULUS)
 if r:raise ValueError(name)
 used=[k for k in vals if __import__('re').search(r'\b'+k+r'\b',lhs.s+' '+rhs.s)]
 parts.append(f'theorem {name} : {lhs.s} = {rhs.s} := by\n  unfold '+ ' '.join(used)+'\n  have he := boundary_spec.2.2\n  dsimp only [phi] at he\n  linear_combination ('+poly(q)+') * he\n')
parts.append('end QuarticLyapunov.Endpoint\n')
(OUT/'EndpointIdentities.lean').write_text('\n'.join(parts))

# Strict sign checks through exact rational Horner intervals.
parts=['module\npublic import QuarticLyapunov.EndpointData\n\npublic section\nset_option maxRecDepth 4096\nset_option maxHeartbeats 0\nnamespace QuarticLyapunov.Endpoint\n']
checks={k: (v[k], True) for k in ['d0','d1','d2','md0','md1','md2','detM']}
