  steps.append(f'  have s{idx+1} := {rule} (c := {rat(c)}) hb s{idx} hl {extra}')
  # reduce rational interval endpoints to keep the next comparison small
  steps.append(f'  norm_num only [div_nonneg, mul_nonneg] at s{idx+1}') if False else None
