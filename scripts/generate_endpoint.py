  if a>=0:rule='horner_pos';extra=f'(by norm_num : (0:ℝ) ≤ {rat(a)})'; lo,hi=a*LOWER+c,z*UPPER+c
  elif z<=0:rule='horner_neg';extra=f'(by norm_num : {rat(z)} ≤ (0:ℝ))';lo,hi=a*UPPER+c,z*LOWER+c
